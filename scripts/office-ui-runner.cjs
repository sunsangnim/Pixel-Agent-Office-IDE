const { app, BrowserWindow } = require('electron')
const assert = require('node:assert/strict')
const { resolve, join } = require('node:path')
const { mkdtempSync, writeFileSync } = require('node:fs')
const fixture = mkdtempSync(join(resolve('out'), 'office-ui-profile-'))
app.setPath('userData', fixture)
const delay = ms => new Promise(r => setTimeout(r, ms))
app.whenReady().then(async () => {
  const win = new BrowserWindow({ show: false, width: 1500, height: 950, webPreferences: { backgroundThrottling: false, offscreen: true } })
  const js = code => win.webContents.executeJavaScript(code)
  const wait = async condition => {
    for(let i=0;i<160;i++){if(await js(condition))return;await delay(100)}
    throw Error(`Timed out: ${condition}`)
  }
  const send = async text => {
    await js(`(()=>{const input=document.querySelector('.chat-input-row textarea');Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype,'value').set.call(input,${JSON.stringify(text)});input.dispatchEvent(new Event('input',{bubbles:true}))})()`)
    await delay(50)
    await js(`document.querySelector('.chat-input-row textarea').dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',code:'Enter',bubbles:true,cancelable:true}))`)
    await delay(100)
  }
  const emitState = async (state,reason='') => {await js(`window.emit('state',{ptyId:'pty-0',state:${JSON.stringify(state)},reason:${JSON.stringify(reason)},timestamp:Date.now()})`);await delay(50)}
  const emitData = text => js(`window.emit('data',{ptyId:'pty-0',data:${JSON.stringify(text)}})`)
  const open = async query => {
    await win.loadFile(resolve('out/office-ui/__tests__/office-ui.html'), query ? { query } : {})
    await wait('window.scene?.actors.size===3 && !!document.querySelector(".chat-input-row textarea")')
  }
  await open()
  await send('클부장 대표실로 오게나')
  assert.deepEqual(await js('window.calls'), [], 'local movement never starts planning or a CLI')
  await js('window.advance(30)')
  await wait('!!document.querySelector(".office-dialogue")')
  assert.equal(await js('window.scene.actors.get("claude-code:lead").bubble.text'), '')
  assert.equal(await js('window.scene.actors.get("claude-code:lead").container.x'), await js('window.scene.furniture.get("representative-desk").image.x'))
  assert.match(await js('document.querySelector(".office-dialogue").textContent'), /대표님, 부르셨나요/)
  assert.equal(await js('document.querySelector(".office-dialogue img").complete'), true)
  await delay(500)
  writeFileSync(join(fixture,'dialogue.png'),(await win.webContents.capturePage()).toPNG())
  // Input keeps its normal key handling while the dialogue is visible.
  assert.equal(await js(`document.querySelector('.chat-input-row textarea').dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',shiftKey:true,bubbles:true,cancelable:true}))`),true)
  await send('코차장님 대표실로 와')
  await js('window.advance(30)')
  await wait('document.querySelector(".office-dialogue-footer")?.textContent.includes("남은 대화 1")')
  await js('document.activeElement?.blur();document.body.dispatchEvent(new KeyboardEvent("keydown",{key:"Enter",bubbles:true,cancelable:true}))')
  await wait('document.querySelector(".office-dialogue figcaption")?.textContent.includes("Codex")')
  await delay(400)
  await js('document.querySelector(".office-dialogue-footer button").focus();document.activeElement.dispatchEvent(new KeyboardEvent("keydown",{key:"Escape",bubbles:true,cancelable:true}))')
  await wait('!document.querySelector(".office-dialogue")')
  await js('window.advance(10)')
  assert.equal(await js('!!document.querySelector(".office-dialogue")'),false,'arrival greeting does not repeat')
  await send('자리로 돌아가게')
  await js('window.advance(30)')
  assert.equal(await js('window.scene.actors.get("codex-cli:lead").chairId'),'chair-1-0','unnamed return addresses the last speaker')
  assert.equal(await js('window.scene.actors.get("claude-code:lead").actor.presence'),'representativeVisit')
  await send('클부장 자리로 돌아가게')
  await js('window.advance(30)')
  assert.equal(await js('window.scene.actors.get("claude-code:lead").chairId'),'chair-0-0')
  assert.deepEqual(await js('window.calls'),[])
  console.log('PASS App commands: desk front, no documents/CLI, dialogue portrait/queue/keys, no speech bubble dialogue, return to own seat')

  await emitState('waiting','작업 폴더 신뢰 승인 대기')
  await wait('document.querySelector(".office-dialogue")?.dataset.requestKind==="permission"')
  assert.match(await js('document.querySelector(".office-dialogue").textContent'),/신뢰 승인 대기/)
  await js(`document.body.dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',bubbles:true,cancelable:true}))`)
  assert.deepEqual(await js('window.calls'),[],'Enter never grants a permission')
  await js(`[...document.querySelectorAll('.office-dialogue button')].find(b=>b.textContent==='권한 요청 확인 · 응답').click()`)
  await wait('!!document.querySelector(".office-dialogue .xterm")')
  await delay(250)
  assert.deepEqual(await js('window.calls'),[],'opening the real request screen sends no response')
  writeFileSync(join(fixture,'permission.png'),(await win.webContents.capturePage()).toPNG())
  // Only explicit input into the embedded CLI is forwarded, to that request's PTY.
  await js('document.querySelector(".office-dialogue .xterm-helper-textarea").focus()')
  win.webContents.sendInputEvent({type:'keyDown',keyCode:'Down'})
  win.webContents.sendInputEvent({type:'keyUp',keyCode:'Down'})
  await wait('window.calls.some(c=>Array.isArray(c)&&c[0]==="write")')
  assert.equal(await js('window.calls.filter(c=>c[0]==="write").at(-1)[1]'),'pty-0')
  await js('window.calls=[];document.activeElement?.blur()')
  await js('document.querySelector(".office-dialogue-close").click()')
  await wait('!document.querySelector(".office-dialogue")')
  await emitState('waiting','작업 폴더 신뢰 승인 대기')
  assert.equal(await js('!!document.querySelector(".office-dialogue")'),false,'same prompt redraw does not reopen dismissal')
  await js('document.querySelector(".office-request-tray button").click()')
  await wait('!!document.querySelector(".office-dialogue")')
  await emitState('ready')
  await wait('!document.querySelector(".office-dialogue")')
  await emitState('waiting','파일 수정 권한 요청')
  await wait('document.querySelector(".office-dialogue")?.textContent.includes("파일 수정 권한 요청")')
  await js(`window.emit('state',{ptyId:'pty-1',state:'waiting',reason:'다른 요청',timestamp:Date.now()})`)
  await wait('document.querySelectorAll(".office-request-tray button").length===2')
  await js('document.querySelector(".office-dialogue-close").click()')
  await wait('document.querySelector(".office-dialogue figcaption")?.textContent.includes("Codex")')
  await js(`window.emit('state',{ptyId:'pty-1',state:'ready',timestamp:Date.now()})`)
  await emitState('ready')
  await wait('!document.querySelector(".office-request-tray")')
  console.log('PASS permission dialogue lifecycle: actual request view, no automatic approval, dismissal/reopen, repeat episode, multiple agents')

  await send('@Claude 테스트 기능 만들어줘')
  await wait('document.querySelector(".office-dialogue")?.dataset.requestKind==="planning"')
  await emitState('waiting','작업 폴더 신뢰 승인 대기')
  await wait('document.querySelector(".office-dialogue")?.dataset.requestKind==="permission"')
  assert.match(await js('document.querySelector(".office-dialogue").textContent'),/신뢰 승인 대기/)
  await emitData('Accessing workspace\nYes, I trust this folder')
  await emitState('completed')
  assert.equal(await js('window.calls.includes("readSpec")'),false,'startup cannot complete a plan')
  await emitState('working','프롬프트 전달')
  await emitData('4. 완료되면 "기획 완료"라고 짧게 보고하세요.\n')
  await emitState('completed')
  assert.equal(await js('window.calls.includes("readSpec")'),false,'echoed instruction cannot complete a plan')
  await emitState('error','테스트 오류')
  assert.match(await js('document.querySelector(".office-dialogue").textContent'),/테스트 오류/)
  await js(`[...document.querySelectorAll('button')].find(b=>b.textContent==='기획 취소').click()`)
  assert.equal(await js('!!document.querySelector(".office-dialogue-request")'),false)
  assert.equal(await js('window.calls.some(c=>Array.isArray(c)&&c[0]==="cancel")'),false,'failed capture already ended')
  await send('@Claude 다른 기능 만들어줘')
  await emitState('working','프롬프트 전달')
  await emitData('기획 완료\n')
  await emitState('completed')
  await wait('document.querySelector(".office-dialogue")?.dataset.requestKind==="approval"')
  assert.equal(await js('window.calls.includes("readSpec")'),true)
  const beforeApproval = await js('window.calls.filter(c=>Array.isArray(c)&&c[0]==="prompt").length')
  await js(`document.body.dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',bubbles:true,cancelable:true}))`)
  assert.equal(await js('window.calls.filter(c=>Array.isArray(c)&&c[0]==="prompt").length'),beforeApproval)
  assert.match(await js('document.querySelector(".office-dialogue-spec").textContent'),/테스트 기획/)
  writeFileSync(join(fixture,'approval.png'),(await win.webContents.capturePage()).toPNG())
  await js(`[...document.querySelectorAll('.office-dialogue button')].find(b=>b.textContent==='반려').click()`)
  assert.equal(await js(`[...document.querySelectorAll('.office-dialogue button')].find(b=>b.textContent==='반려 사유 전송').disabled`),true)
  await js(`(()=>{const input=document.querySelector('.office-dialogue-feedback');Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype,'value').set.call(input,'테스트 조건을 추가해주세요');input.dispatchEvent(new Event('input',{bubbles:true}))})()`)
  await delay(50)
  await js(`document.querySelector('.office-dialogue-feedback').dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',bubbles:true,cancelable:true}))`)
  await wait('document.querySelector(".office-dialogue")?.dataset.requestKind==="planning"')
  assert.match(await js('window.calls.filter(c=>Array.isArray(c)&&c[0]==="prompt").at(-1)[2]'),/테스트 조건을 추가해주세요/)
  await emitState('working','프롬프트 전달')
  await emitData('기획 완료\n')
  await emitState('completed')
  await wait('document.querySelector(".office-dialogue")?.dataset.requestKind==="approval"')
  await js(`document.querySelector('.office-dialogue-approve').click()`)
  await delay(100)
  await emitData('요청하신 작업을 완료했습니다.\n')
  await emitState('completed')
  await wait('document.querySelector(".office-dialogue")?.textContent.includes("요청하신 작업을 완료")')
  assert.match(await js('document.querySelector(".office-dialogue figcaption").textContent'),/Claude/)
  console.log('PASS planning trust/error/echo gating, actual completion review, agent response shown in dialogue')

  for(const query of [{recover:'1'},{recoverBare:'1'}]) {
    await open(query)
    await wait('window.calls.some(c=>Array.isArray(c)&&c[0]==="cancel")')
    assert.equal(await js('window.calls.includes("prepare")'),false)
    await js('window.advance(30)')
    assert.equal(await js('window.scene.actors.get("claude-code:lead").chairId'),'chair-0-0')
    assert.equal(await js('!!document.querySelector(".office-dialogue-request")'),false)
  }
  console.log('PASS recovery cancels both mentioned and contextual misrouted return commands without documents or CLI prompts')
  await open({recoverAlias:'1'})
  await wait('window.calls.some(c=>Array.isArray(c)&&c[0]==="cancel")')
  await js('window.advance(30)')
  assert.equal(await js('window.scene.actors.get("claude-code:lead").actor.presence'),'representativeVisit')
  assert.equal(await js('window.scene.actors.get("claude-code:lead").container.x'), await js('window.scene.furniture.get("representative-desk").image.x'))
  assert.equal(await js('window.calls.includes("prepare")'),false)
  assert.equal(await js('window.calls.some(c=>Array.isArray(c)&&c[0]==="prompt")'),false)
  assert.equal(await js('!!document.querySelector(".office-dialogue-request")'),false)
  console.log('PASS recovery cancels misrouted title-alias summons and visits the desk without planning')
  console.log(`Screenshot: ${join(fixture,'dialogue.png')}`)
  app.quit()
}).catch(error=>{console.error(error);app.exit(1)})
